-- Gerar presenças para todas as aulas concluídas
INSERT INTO tb_presenca (presente, data_registro, id_aluno, id_aula)
SELECT 
    CASE 
        WHEN RAND() > 0.15 THEN 1  -- 85% de presença em média
        ELSE 0 
    END as presente,
    a.data_aula as data_registro,
    h.id_aluno as id_aluno,
    a.id_aula as id_aula
FROM tb_aula a
JOIN tb_historico_aluno h ON a.id_turma = h.id_turma
WHERE a.aula_concluida = 1
AND a.data_aula BETWEEN '2023-01-01' AND CURDATE()
AND h.data_saida = '9999-01-01';

