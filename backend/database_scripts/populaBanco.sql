-- SCRIPT PARA INSERIR PAGAMENTOS:

INSERT INTO `tb_pagamentos` (`data_pagamento`, `id_aluno`, `id_mensalidade`)
WITH RECURSIVE months AS (
    SELECT '2023-01-01' as month_start,
           LAST_DAY('2023-01-01') as month_end,
           0 as month_num
    UNION ALL
    SELECT DATE_ADD(month_start, INTERVAL 1 MONTH),
           LAST_DAY(DATE_ADD(month_start, INTERVAL 1 MONTH)),
           month_num + 1
    FROM months
    WHERE DATE_ADD(month_start, INTERVAL 1 MONTH) <= CURDATE()
),
alunos_nao_bolsistas AS (
    SELECT id_aluno 
    FROM tb_aluno 
    WHERE bolsista = 0
),
pagamentos_gerados AS (
    SELECT 
        m.month_start as data_pagamento,
        a.id_aluno,
        2 as id_mensalidade,
        CASE 
            WHEN RAND() <= 0.9 THEN DATE_ADD(m.month_start, INTERVAL 5 DAY)
            WHEN RAND() <= 0.7 THEN DATE_ADD(m.month_start, INTERVAL 10 DAY)
            WHEN RAND() <= 0.5 THEN DATE_ADD(m.month_start, INTERVAL 15 DAY)
            ELSE DATE_ADD(m.month_start, INTERVAL 20 DAY)
        END as data_real_pagamento,
        CASE WHEN RAND() > 0.05 THEN 1 ELSE 0 END as pagou_esse_mes
    FROM months m
    CROSS JOIN alunos_nao_bolsistas a
    WHERE m.month_start >= '2023-01-01'
    AND m.month_start <= CURDATE()
)
SELECT 
    data_real_pagamento as data_pagamento,
    id_aluno,
    id_mensalidade
FROM pagamentos_gerados
WHERE pagou_esse_mes = 1
AND NOT EXISTS (
    SELECT 1 FROM tb_pagamentos p 
    WHERE p.id_aluno = pagamentos_gerados.id_aluno 
    AND YEAR(p.data_pagamento) = YEAR(pagamentos_gerados.data_real_pagamento)
    AND MONTH(p.data_pagamento) = MONTH(pagamentos_gerados.data_real_pagamento)
)
ORDER BY id_aluno, data_real_pagamento;

